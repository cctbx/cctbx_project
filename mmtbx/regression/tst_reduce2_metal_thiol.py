def test_no_cell_symmetry():
  '''input without a cell: thiol_metal_sites() gets no crystal symmetry (not
  the working box) in add, place and optimize'''
  from mmtbx.hydrogens import reduce_hydrogen
  seen = []
  orig = reduce_hydrogen.thiol_metal_sites
  class spy(orig):
    def __init__(self, model, crystal_symmetry=None):
      seen.append(crystal_symmetry)
      orig.__init__(self, model, crystal_symmetry)
  no_cell = lambda t: '\n'.join(l for l in t.split('\n')
                                if not l.startswith('CRYST1'))
  reduce_hydrogen.thiol_metal_sites = spy
  try:
    for approach, model in (('add', m_zn_fixture), ('place', m_zn_fixture),
                            ('optimize', m_zn_fixture_H)):
      del seen[:]
      run(no_cell(model), 'tst_reduce2_metal_thiol_nocell_' + approach,
        ['approach=' + approach])
      assert seen and all(cs is None for cs in seen), (approach, seen)
  finally:
    reduce_hydrogen.thiol_metal_sites = orig

