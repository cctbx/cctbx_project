def test_occupancy_and_altlocs():
  '''constructed from the Zn-Cys model; per case the expected HG sites and
  report. On HEAD the HG sites of c2, c2b, c3 and c4b are the same (mcl
  proxies, valence count per conformer), but there is no report; c3b, c4,
  c5 and occupancy 0 lose their HG there'''
  cases = [
    # blank SG; O split A/B 0.5; Zn in A 0.5: HG/A covered, HG/B no metal
    (m_c2_sharedSG, 'c2', [('A', False), ('B', True)], 1, 0),
    # SG split A/B 0.5; Zn in B 0.5 near SG B only
    (m_c2b_splitSG, 'c2b', [('B', False), ('A', True)], 1, 0),
    # one Zn site, alternates A/B 0.5 + 0.5 = 1.0
    (m_c3_altmetal, 'c3', [('', False)], 1, 0),
    # 0.3 + 0.3 = 0.6 < 1.0
    (m_c3b_altmetal_low, 'c3b', [('', True)], 0, 1),
    # two Zn sites 0.6 and 0.4: the largest, 0.6, < 1.0
    (m_c4_two_sites, 'c4', [('', True)], 0, 1),
    # bridging, two Zn at 1.0
    (m_c4b_bridging, 'c4b', [('', False)], 1, 0),
    # Zn 0.5 on SG 1.0
    (m_c5_partial, 'c5', [('', True)], 0, 1),
    # Zn at occupancy 0 does not count, nothing reported
    (m_zn_occ0, 'occ0', [('', True)], 0, 0),
    ]
  descs = {}
  for model, name, expected, n_not_placed, n_unresolved in cases:
    out, desc = run(model, 'tst_reduce2_metal_thiol_' + name, ['approach=add'])
    descs[name] = desc
    for altloc, present in expected:
      assert has(out, 'HG', '48', altloc) == present, (name, altloc, out)
    assert len(section(desc, NOT_PLACED)) == n_not_placed, (name, desc)
    assert len(section(desc, UNRESOLVED)) == n_unresolved, (name, desc)
  desc = descs['c4']
  assert ('SG occupancy 1.00 exceeds coordinating ZN occupancy 0.60. '
    'Protonation may differ between bound and unbound populations. HG was '
    'added using the default thiol state; review this site.') in desc, desc

