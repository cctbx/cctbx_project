def _inject_og_zn():
  '''mcl.update plus a metal-coordination proxy SER OG - ZN'''
  orig = mcl.update
  def update(grm, pdb_hierarchy, *args, **kwds):
    orig(grm, pdb_hierarchy, *args, **kwds)
    cache = pdb_hierarchy.atom_selection_cache()
    i = cache.selection('resname SER and name OG').iselection()
    j = cache.selection('resname ZN').iselection()
    if i.size() != 1 or j.size() != 1: return
    grm.add_new_bond_restraints_in_place(
      proxies=[geometry_restraints.bond_simple_proxy(
        i_seqs=[i[0], j[0]], distance_ideal=2.05, weight=400, slack=0,
        top_out=False, limit=1,
        origin_id=linking_class().get_origin_id('metal coordination'))],
      sites_cart=pdb_hierarchy.atoms().extract_xyz())
  return orig, update

