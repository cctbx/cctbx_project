def run(model_text, prefix, extra_args=()):
  fn_in = prefix + ".pdb"
  fn_out = prefix + "_out.pdb"
  fn_desc = prefix + "_out.txt"
  with open(fn_in, "w") as f:
    f.write(model_text)
  for fn in (fn_out, fn_desc):
    if os.path.exists(fn): os.remove(fn)
  args = [fn_in, "output.filename=" + fn_out,
    "output.description_file_name=" + fn_desc, "overwrite=True"]
  run_program(program_class=reduce2.Program, logger=null_out(),
    args=args + list(extra_args))
  with open(fn_out) as f:
    model_out = f.read()
  with open(fn_desc) as f:
    return model_out, f.read()

def h_sites(model_text):
  '''{(name, altloc, resname, resseq)} of the H/D'''
  h = iotbx.pdb.input(source_info=None, lines=model_text).construct_hierarchy()
  return set((a.name.strip(), a.parent().altloc, a.parent().resname.strip(),
              a.parent().parent().resseq.strip())
             for a in h.atoms() if a.element.strip().upper() in ('H', 'D'))

def has(model_text, name, resseq, altloc=None):
  return any(n == name and r == resseq and (altloc is None or alt == altloc)
             for n, alt, rn, r in h_sites(model_text))

def section(desc, title):
  '''the lines of a report section of the description'''
  lines = desc.split('\n')
  if title not in desc: return []
  i = [k for k, l in enumerate(lines) if l.startswith(title)][0]
  out = []
  for l in lines[i+1:]:
    if not l.startswith('  ') or l.startswith('  Time'): break
    if l.startswith('  to drop it: '): break
    out.append(l)
  return out

def drop_hint(desc):
  '''the rebuild hint after the supplied-H list'''
  hints = [l[len('  to drop it: '):] for l in desc.split('\n')
           if l.startswith('  to drop it: ')]
  return hints[0] if len(hints) == 1 else hints

def without_hd(model_text):
  return '\n'.join(l for l in model_text.split('\n')
    if not (l.startswith(('ATOM', 'HETATM')) and l[76:78].strip() in ('H', 'D')))

def test_1brf():
  '''Fe(Cys)4, no proxy (mcl has no Fe(Cys)4 hook): no HG, listed; supplied
  HG kept, with the note; no metal-coordination proxy'''
  fn = libtbx.env.find_in_repositories(
    relative_path="mmtbx/regression/pdbs/Fe_1brf_snip_reduced.pdb",
    test=os.path.isfile)
  with open(fn) as f: model = without_hd(f.read())
  cys = ('5', '8', '38', '41')
  for approach in ('add', 'place'):
    out, desc = run(model, 'tst_reduce2_metal_thiol_1brf_' + approach,
      ['approach=' + approach])
    for r in cys: assert not has(out, 'HG', r), r
    listed = section(desc, NOT_PLACED)
    assert sorted(l.split()[3] for l in listed) == sorted(cys), listed
  # supplied: HG built without the Fe, then the Fe put back
  fe = [l for l in model.split('\n') if l[17:20] == ' FE']
  out, desc = run('\n'.join(l for l in model.split('\n') if l not in fe),
    'tst_reduce2_metal_thiol_1brf_nofe', ['approach=place'])
  supplied = '\n'.join([l for l in out.split('\n') if not l.startswith('END')]
    + fe)
  out, desc = run(supplied, 'tst_reduce2_metal_thiol_1brf_supplied',
    ['approach=add', 'keep_existing_H=True'])
  for r in cys: assert has(out, 'HG', r), r
  listed = section(desc, SUPPLIED)
  assert len(listed) == 4 and all(l.endswith(NO_PROXY) for l in listed), listed
  assert drop_hint(desc) == 'keep_existing_H=False', desc

