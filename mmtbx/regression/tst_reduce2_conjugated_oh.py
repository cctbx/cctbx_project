def bonded_by_distance(atoms):
  '''Bonded-neighbor lists from distances (H 1.45 A, others 1.9 A) for
  isolated residues without restraints'''
  bonded = {}
  for a in atoms:
    bonded[a] = []
  for i, a in enumerate(atoms):
    for b in atoms[i+1:]:
      cut = 1.45 if a.element_is_hydrogen() or b.element_is_hydrogen() else 1.9
      if a.element_is_hydrogen() and b.element_is_hydrogen():
        continue
      if a.distance(b) < cut:
        bonded[a].append(b)
        bonded[b].append(a)
  return bonded

def test_scope():
  '''Conjugated O-H in scope: Tyr HH, the CRO phenol H, Asp HD2 (with OD1 as
  the second carboxyl O), the BCT HO3 (no second O: its C has two other O);
  out: Ser HG, the CRO OG1 H (sp3), RNA HO2', the amidine N-H of BEN (planar,
  but on N), the S-H of a thiophenol (TPL, built from Tyr A 199)'''
  h = iotbx.pdb.input(source_info=None, lines=m_scope).construct_hierarchy()
  atoms = h.atoms()
  atoms.reset_i_seq()
  bonded = bonded_by_distance(list(atoms))
  def scope(resname, name):
    for a in atoms:
      if a.parent().resname.strip() == resname and a.name.strip() == name:
        inScope, other = Movers.ConjugatedHydrogenScope(a, bonded)
        return inScope, (other.name.strip() if other is not None else None)
  assert scope('TYR', 'HH') == (True, None), scope('TYR', 'HH')
  assert scope('CRO', 'HOH') == (True, None), scope('CRO', 'HOH')
  assert scope('ASP', 'HD2') == (True, 'OD1'), scope('ASP', 'HD2')
  assert scope('SER', 'HG') == (False, None), scope('SER', 'HG')
  assert scope('CRO', 'HOG1') == (False, None), scope('CRO', 'HOG1')
  assert scope('G', "HO2'") == (False, None), scope('G', "HO2'")
  assert scope('BEN', 'HN1') == (False, None), scope('BEN', 'HN1')
  assert scope('TPL', 'HS1') == (False, None), scope('TPL', 'HS1')
  assert scope('BCT', 'HO3') == (True, None), scope('BCT', 'HO3')

def bct_rotator(reverse):
  '''MoverSingleHydrogenRotator for the BCT HO3 (GeoStd ideal coordinates),
  with the bonded-neighbor lists in the order given or reversed'''
  lines = [l for l in m_scope.splitlines() if l[17:20] == 'BCT']
  h = iotbx.pdb.input(source_info=None, lines=lines).construct_hierarchy()
  atoms = h.atoms()
  atoms.reset_i_seq()
  a = dict((x.name.strip(), x) for x in atoms)
  bonded = {a['HO3']: [a['O3']], a['O3']: [a['C'], a['HO3']],
    a['C']: [a['O1'], a['O2'], a['O3']], a['O1']: [a['C']], a['O2']: [a['C']]}
  if reverse:
    bonded = dict((k, list(reversed(v))) for k, v in bonded.items())
  infos = []
  for x in atoms:
    e = probeExt.ExtraAtomInfo()
    e.vdwRadius = 1.0 if x.element_is_hydrogen() else 1.5
    infos.append(e)
  extras = probeExt.ExtraAtomInfoMap(atoms, infos)
  class Item:
    def __init__(self, n, a2): self.n = n; self.a2 = a2
  mover = Movers.MoverSingleHydrogenRotator(a['HO3'], bonded, extras,
    {a['HO3'].i_seq: Item(0, a['O1'].i_seq)})
  mover._model = h  # keep the hierarchy that the atoms belong to
  return mover

def test_bicarbonate_order():
  '''BCT HO3: the preference at each H position, and the preferred positions,
  do not depend on the order of the bonded-neighbor lists (with a syn term to
  "the other O" they did: syn to O2 in one order, to O1 in the other)'''
  def preferred(reverse):
    coarse = bct_rotator(reverse).CoarsePositions()
    energies = {}
    for pos, e in zip(coarse.positions, coarse.preferenceEnergies):
      energies[tuple(round(c, 3) for c in pos[0])] = round(e, 6)
    best = max(energies.values())
    return energies, set(k for k, e in energies.items() if e == best)
  normal, reverse = preferred(False), preferred(True)
  common = set(normal[0]) & set(reverse[0])
  assert len(common) >= 2, (normal[0], reverse[0])
  for k in common:
    assert normal[0][k] == reverse[0][k], (k, normal[0][k], reverse[0][k])
  assert normal[1] == reverse[1], (normal[1], reverse[1])

def run(model_text, prefix, extra=()):
  '''reduce2; returns {(chain, resseq, name): atom} of the output'''
  fn_in = prefix + '_in.pdb'
  fn_out = prefix + '_out.pdb'
  fn_desc = prefix + '_desc.txt'
  with open(fn_in, "w") as f:
    f.write(model_text)
  for fn in (fn_out, fn_desc):
    if os.path.exists(fn): os.remove(fn)
  run_program(program_class=reduce2.Program, logger=null_out(),
    args=[fn_in, "output.filename=" + fn_out,
      "output.description_file_name=" + fn_desc, "overwrite=True"] + list(extra))
  atoms = {}
  for rg in iotbx.pdb.input(fn_out).construct_hierarchy().residue_groups():
    for a in rg.atoms():
      atoms[(rg.parent().id, rg.resseq.strip(), a.name.strip())] = a
  return atoms

def dihedral(atoms, key, names):
  return scitbx.math.dihedral_angle(sites=[atoms[key + (n,)].xyz for n in names], deg=True)

def plane_dev(d):
  return min(abs(d), 180 - abs(d))

def angle(a, b, c):
  col = scitbx.matrix.col
  return math.degrees((col(a.xyz) - col(b.xyz)).angle(col(c.xyz) - col(b.xyz)))

def test_tyr_without_partner():
  '''4WSC Tyr A 199 HH has no acceptor; it ends in the ring plane (before: 85
  degrees out, kept by contact dots)'''
  atoms = run(m_4wsc_tyr, 'tst_reduce2_conjugated_oh_4wsc',
    ["approach=add", "add_flip_movers=True"])
  d = dihedral(atoms, ('A', '199'), ('CE1', 'CZ', 'OH', 'HH'))
  assert plane_dev(d) <= 15, d

def test_tyr_out_of_plane_hbond():
  '''8EYP Tyr B 1016 HH keeps its out-of-plane H-bond to Tyr B 1008 OH (as in
  the deposited neutron model): the preference does not outweigh an H-bond'''
  atoms = run(m_8eyp_tyr, 'tst_reduce2_conjugated_oh_8eyp',
    ["approach=add", "add_flip_movers=True"])
  d = dihedral(atoms, ('B', '1016'), ('CE1', 'CZ', 'OH', 'HH'))
  hh, oh = atoms[('B', '1016', 'HH')], atoms[('B', '1016', 'OH')]
  acc = atoms[('B', '1008', 'OH')]
  assert plane_dev(d) > 30, d
  assert hh.distance(acc) < 2.2 and angle(oh, hh, acc) > 150, (
    hh.distance(acc), angle(oh, hh, acc))

