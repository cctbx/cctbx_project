def test_scorer_follows_map():
  '''A flag changed in the ExtraAtomInfoMap after the DotScorer was built (as
  the Optimizer's setMoverState does) changes the score: H dots on an N 2 A
  away score as an H-bond while the N is an acceptor and as a clash after.'''
  atoms = iotbx.pdb.input(source_info=None,
    lines=m_pair).construct_hierarchy().atoms()
  atoms.reset_i_seq()
  n, h = atoms[0], atoms[1]
  infos = [probeExt.ExtraAtomInfo(1.55, True, False),
    probeExt.ExtraAtomInfo(1.05, False, True)]
  extra = probeExt.ExtraAtomInfoMap(atoms, infos)
  scorer = probeExt.DotScorer(extra)
  sq = probeExt.SpatialQuery(atoms)
  sphere = probeExt.DotSphereCache(16).get_sphere(1.05)
  def score():
    return scorer.score_dots(h, 1.0, sq, 1.05 + 1.55, 0.25, [], sphere.dots(),
      sphere.density(), False, False).totalScore()
  acceptor = score()
  e = extra.getMappingFor(n)
  e.isAcceptor = False
  extra.setMappingFor(n, e)
  not_acceptor = score()
  assert acceptor > 0 and not_acceptor < 0, (acceptor, not_acceptor)

def run(model_text, prefix, extra=()):
  '''reduce2 add with flips; returns
  (description, {(chain, resseq, name): atom})'''
  fn_in = prefix + '_in.pdb'
  fn_out = prefix + '_out.pdb'
  fn_desc = prefix + '_desc.txt'
  with open(fn_in, "w") as f:
    f.write(model_text)
  for fn in (fn_out, fn_desc):
    if os.path.exists(fn): os.remove(fn)
  run_program(program_class=reduce2.Program, logger=null_out(),
    args=[fn_in, "approach=add", "add_flip_movers=True",
      "output.filename=" + fn_out, "output.description_file_name=" + fn_desc,
      "overwrite=True"] + list(extra))
  with open(fn_desc) as f:
    desc = f.read()
  atoms = {}
  for rg in iotbx.pdb.input(fn_out).construct_hierarchy().residue_groups():
    for a in rg.atoms():
      atoms[(rg.parent().id, rg.resseq.strip(), a.name.strip())] = a
  return desc, atoms

def pose(desc, label):
  for l in desc.split('\n'):
    m = re.match(r"\s*HisFlip at " + label + r" NE2 .* pose (.*)$", l)
    if m:
      return m.group(1)
  return None

def rotator(desc, label):
  '''(number of potential nearby acceptors, final angle) of a
  single-hydrogen rotator'''
  n = re.search(r"Added MoverSingleHydrogenRotator \d+ to " + label +
    r" with (\d+) potential nearby acceptors", desc)
  a = re.search(r"SingleHydrogenRotator at " + label +
    r" Initial .* pose Angle (\S+) deg", desc)
  return int(n.group(1)), float(a.group(1))

def angle(a, b, c):
  col = scitbx.matrix.col
  return math.degrees((col(a.xyz) - col(b.xyz)).angle(col(c.xyz) - col(b.xyz)))

def test_6vw1_his_b34():
  '''His B 34 keeps HE2; Tyr F 453 HH donates to the bare ND1'''
  desc, atoms = run(m_6vw1, 'tst_reduce2_his_acceptor_6vw1')
  p = pose(desc, 'chain B HIS 34')
  assert p.startswith('Unflipped HD1NotPlaced HE2Placed'), p
  assert ('B', '34', 'HD1') not in atoms and ('B', '34', 'HE2') in atoms
  hh, oh = atoms[('F', '453', 'HH')], atoms[('F', '453', 'OH')]
  nd1 = atoms[('B', '34', 'ND1')]
  assert hh.distance(nd1) < 2.3 and angle(oh, hh, nd1) > 120, (
    hh.distance(nd1), angle(oh, hh, nd1))

def test_4kw8_his169():
  '''His 169 loses HE2; Thr 167 HG1 donates to the bare NE2'''
  desc, atoms = run(m_4kw8, 'tst_reduce2_his_acceptor_4kw8')
  p = pose(desc, 'chain A HIS 169')
  assert p.startswith('Unflipped HD1Placed HE2NotPlaced'), p
  assert ('A', '169', 'HE2') not in atoms and ('A', '169', 'HD1') in atoms
  hg, og = atoms[('A', '167', 'HG1')], atoms[('A', '167', 'OG1')]
  ne2 = atoms[('A', '169', 'NE2')]
  assert hg.distance(ne2) < 2.6 and angle(og, hg, ne2) > 150, (
    hg.distance(ne2), angle(og, hg, ne2))

def test_rotator_candidate_from_his_state():
  '''Tyr F 453 HH: His B 34 ND1 carries HD1 in the His Mover's starting
  state, so it is not an acceptor then, but is one in the states without HD1;
  it stays a candidate and HH takes the angle aimed at it (without: 3
  candidates, 0.1 deg)'''
  desc, atoms = run(m_6vw1, 'tst_reduce2_his_acceptor_candidate')
  n, a = rotator(desc, 'chain F TYR 453 HH')
  assert n == 4 and abs(a - 14.7) < 3, (n, a)

def zinc_on_copy(model_text):
  '''chain F one cell along a, so His B 34 meets Tyr F 453 through a copy; a Zn
  2.25 A from His B 34 ND1 along the ring normal'''
  inp = iotbx.pdb.input(source_info=None, lines=model_text)
  cs = inp.crystal_symmetry()
  h = inp.construct_hierarchy()
  a = scitbx.matrix.col(cs.unit_cell().orthogonalize((1, 0, 0)))
  ring = {}
  for at in h.atoms():
    rg = at.parent().parent()
    if rg.parent().id == 'F':
      at.xyz = tuple(scitbx.matrix.col(at.xyz) + a)
    elif rg.parent().id == 'B' and rg.resseq.strip() == '34':
      ring[at.name.strip()] = scitbx.matrix.col(at.xyz)
  nd1 = ring['ND1']
  normal = (ring['CG'] - nd1).cross(ring['CE1'] - nd1).normalize()
  zn = nd1 + 2.25 * normal
  lines = [l for l in h.as_pdb_string(crystal_symmetry=cs).splitlines()
    if not l.startswith('END')]
  lines.append('HETATM  990 ZN    ZN Z   1    %8.3f%8.3f%8.3f  1.00 10.00          ZN'
    % tuple(zn))
  return '\n'.join(lines + ['END', ''])

def test_symmetry_copy_candidate():
  '''The ion lock makes His B 34 ND1 an acceptor after its copies took their
  atom info; Tyr F 453 HH, next to the copy, still takes the angle aimed at it
  (judged by the copy's flags: 0.1 deg)'''
  desc, atoms = run(zinc_on_copy(m_6vw1), 'tst_reduce2_his_acceptor_copy',
    ["include_symmetric_copies=True"])
  assert ("Not adding Hydrogen to chain B HIS 34 ND1 and marking as an "
    "acceptor (ionic bond to ZN)") in desc, desc
  n, a = rotator(desc, 'chain F TYR 453 HH')
  assert abs(a - 14.7) < 3, (n, a)

