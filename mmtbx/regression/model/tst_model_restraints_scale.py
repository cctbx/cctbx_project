def get_model():
  pdb_inp = iotbx.pdb.input(source_info=None, lines=pdb_str)
  model = mmtbx.model.manager(model_input=pdb_inp, log=null_out())
  model.process(make_restraints=True)
  return model

def get_weights(model):
  g = model.get_restraints_manager().geometry
  simple, asu = g.get_all_bond_proxies(sites_cart = model.get_sites_cart())
  return flex.double([p.weight for p in simple]), \
         flex.double([p.weight for p in g.angle_proxies])

def exercise_model():
  model = get_model()
  # created at first use only
  assert model.rsm is None
  b0, a0 = get_weights(model)
  assert b0.size() > 0 and a0.size() > 0
  # nothing to apply yet
  assert not model.apply_restraints_scale()
  # zero factor: nothing is done
  rank = flex.double(model.size(), 0.9)
  assert not model.scale_restraints(factor = 0, density_rank = rank)
  # scale: scale factors are set, restraints do not change (which
  # restraints get which factor is not tested: the rules are experimental)
  assert model.scale_restraints(factor = 10., density_rank = rank)
  rsm = model.rsm
  assert len(rsm.bond_scales) > 0 and len(rsm.angle_scales) > 0
  b, a = get_weights(model)
  assert approx_equal(b, b0)
  assert approx_equal(a, a0)
  # apply / remove
  def expected():
    g = model.get_restraints_manager().geometry
    simple, asu = g.get_all_bond_proxies(sites_cart = model.get_sites_cart())
    b = flex.double([p.weight * rsm.bond_scales.get(rsm.bond_key(p.i_seqs), 1)
      for p in simple])
    a = flex.double([p.weight * rsm.angle_scales.get(rsm.angle_key(p.i_seqs),
      1) for p in g.angle_proxies])
    return b, a
  b1, a1 = expected()
  assert b1.all_gt(0) and a1.all_gt(0)
  assert not approx_equal(b1, b0, out=None)
  assert not approx_equal(a1, a0, out=None)
  for trial in range(2):
    assert model.apply_restraints_scale()
    assert model.apply_restraints_scale() # second call changes nothing
    b, a = get_weights(model)
    assert approx_equal(b, b1)
    assert approx_equal(a, a1)
    assert model.remove_restraints_scale()
    assert model.remove_restraints_scale()
    b, a = get_weights(model)
    assert approx_equal(b, b0)
    assert approx_equal(a, a0)
  # bond proxies re-generated by the geometry restraints manager while
  # scale factors are applied: scaled weights stay; remove() works after it
  g = model.get_restraints_manager().geometry
  model.apply_restraints_scale()
  g.reset_internals()
  b, a = get_weights(model)
  assert approx_equal(b, b1)
  assert approx_equal(a, a1)
  model.remove_restraints_scale()
  b, a = get_weights(model)
  assert approx_equal(b, b0)
  assert approx_equal(a, a0)
  # scale again: factors accumulate, also if applied at that time
  n_b = len(rsm.bond_scales)
  model.apply_restraints_scale()
  assert model.scale_restraints(factor = 10., density_rank = rank)
  assert rsm.applied()
  assert len(rsm.bond_scales) >= n_b
  b2, a2 = get_weights(model)
  assert not approx_equal(b2, b1, out=None)
  model.remove_restraints_scale()
  b, a = get_weights(model)
  assert approx_equal(b, b0)
  assert approx_equal(a, a0)
  # restraints changed between remove() and apply() (as a restraints update
  # in refinement would do): the changed weight is the one that is scaled
  angle_proxies = g.angle_proxies
  k = None
  for i, p in enumerate(angle_proxies):
    if rsm.angle_key(p.i_seqs) in rsm.angle_scales:
      k = i
      break
  assert k is not None
  w = angle_proxies[k].weight
  angle_proxies[k].weight = w * 3
  model.apply_restraints_scale()
  scale = rsm.angle_scales[rsm.angle_key(angle_proxies[k].i_seqs)]
  assert approx_equal(angle_proxies[k].weight, w * 3 * scale)
  model.remove_restraints_scale()
  assert approx_equal(angle_proxies[k].weight, w * 3)
  angle_proxies[k].weight = w
  # restraints re-made from scratch: scale factors are kept
  model.apply_restraints_scale()
  b2, a2 = get_weights(model)
  model.process(make_restraints=True)
  assert model.rsm is rsm and not rsm.applied()
  b, a = get_weights(model)
  assert approx_equal(b, b0)
  assert approx_equal(a, a0)
  model.apply_restraints_scale()
  b, a = get_weights(model)
  assert approx_equal(b, b2)
  assert approx_equal(a, a2)
  model.remove_restraints_scale()
  # wrong input
  try: model.scale_restraints(factor = 10., density_rank = flex.double(3, 0.5))
  except AssertionError: pass
  else: raise RuntimeError("Exception expected.")

def weights_by_atoms(model):
  """
  {atom labels of a bond or an angle: weight}
  """
  atoms = model.get_hierarchy().atoms()
  g = model.get_restraints_manager().geometry
  simple, asu = g.get_all_bond_proxies(sites_cart = model.get_sites_cart())
  result = {}
  for proxies in [simple, g.angle_proxies]:
    for p in proxies:
      key = tuple(sorted([atoms[i].id_str() for i in p.i_seqs]))
      result[key] = p.weight
  return result

def exercise_select():
  """
  Scale factors follow the atoms when the model is selected.
  """
  model = get_model()
  rank = flex.double(model.size(), 0.9)
  assert model.scale_restraints(factor = 10., density_rank = rank)
  w0 = weights_by_atoms(model)
  model.apply_restraints_scale()
  w1 = weights_by_atoms(model)
  model.remove_restraints_scale()
  n_scaled = len([k for k in w0 if abs(w0[k]-w1[k]) > 1.e-6])
  assert n_scaled > 0
  # remove the first residue: all i_seqs change
  selection = model.selection("not resseq 1")
  assert 0 < selection.count(True) < model.size()
  for applied in [False, True]:
    if applied: model.apply_restraints_scale()
    m = model.select(selection)
    if applied: model.remove_restraints_scale()
    assert m.rsm is not None and m.rsm is not model.rsm
    assert m.rsm.applied() == applied
    assert 0 < len(m.rsm.bond_scales) < len(model.rsm.bond_scales)
    if not applied: assert m.apply_restraints_scale()
    w = weights_by_atoms(m)
    assert len(w) > 0
    n = 0
    for key, weight in w.items():
      assert approx_equal(weight, w1[key])
      if abs(w0[key]-w1[key]) > 1.e-6: n += 1
    assert 0 < n < n_scaled
    m.remove_restraints_scale()
    for key, weight in weights_by_atoms(m).items():
      assert approx_equal(weight, w0[key])

def exercise_moved_atoms():
  """
  Atoms re-ordered behind the back of the manager: scale factors that would
  go to wrong atoms are dropped.
  """
  model = get_model()
  rank = flex.double(model.size(), 0.9)
  assert model.scale_restraints(factor = 10., density_rank = rank)
  rsm = model.rsm
  n = len(rsm.bond_scales) + len(rsm.angle_scales)
  # same number of atoms, the first residue is now the last one
  h = model.get_hierarchy()
  chain = h.only_model().only_chain()
  rg = chain.residue_groups()[0]
  chain.remove_residue_group(rg)
  chain.append_residue_group(rg)
  h.atoms().reset_i_seq()
  m = mmtbx.model.manager(
    model_input      = None,
    pdb_hierarchy    = h,
    crystal_symmetry = model.crystal_symmetry(),
    log              = null_out())
  m.process(make_restraints=True)
  m.rsm = rsm
  rsm.model = m
  b0, a0 = get_weights(m)
  m.apply_restraints_scale()
  assert rsm.n_dropped == n, (rsm.n_dropped, n)
  assert rsm.is_empty()
  b, a = get_weights(m)
  assert approx_equal(b, b0)
  assert approx_equal(a, a0)

def exercise_origin():
  """
  Only restraints of covalent geometry are scaled.
  """
  from cctbx.geometry_restraints.linking_class import linking_class
  other = linking_class().get_origin_id("hydrogen bonds")
  assert other != restraints_scale_manager.origin_id
  rank = flex.double(get_model().size(), 0.9)
  # reference: everything is covalent geometry
  model = get_model()
  assert model.scale_restraints(factor = 10., density_rank = rank)
  rsm = model.rsm
  bond_keys  = sorted(rsm.bond_scales.keys())
  angle_keys = sorted(rsm.angle_scales.keys())
  assert len(bond_keys) > 1 and len(angle_keys) > 1
  # same, with one bond and one angle of a different origin
  model = get_model()
  g = model.get_restraints_manager().geometry
  simple, asu = g.get_all_bond_proxies(sites_cart = model.get_sites_cart())
  n = 0
  for p in simple:
    if rsm.bond_key(p.i_seqs) == bond_keys[0]:
      p.origin_id = other
      g.bond_params_table.lookup(*p.i_seqs).origin_id = other
      n += 1
  for p in g.angle_proxies:
    if rsm.angle_key(p.i_seqs) == angle_keys[0]:
      p.origin_id = other
      n += 1
  assert n == 2
  b0, a0 = get_weights(model)
  assert model.scale_restraints(factor = 10., density_rank = rank)
  assert sorted(model.rsm.bond_scales.keys())  == bond_keys[1:]
  assert sorted(model.rsm.angle_scales.keys()) == angle_keys[1:]
  # a restraint that is not of covalent geometry anymore is left alone
  # even if it has a scale factor
  model.rsm.bond_scales[bond_keys[0]]   = 5.
  model.rsm.angle_scales[angle_keys[0]] = 5.
  model.apply_restraints_scale()
  b1, a1 = get_weights(model)
  g = model.get_restraints_manager().geometry
  simple, asu = g.get_all_bond_proxies(sites_cart = model.get_sites_cart())
  for i, p in enumerate(simple):
    if rsm.bond_key(p.i_seqs) == bond_keys[0]:
      assert approx_equal(b1[i], b0[i])
      assert approx_equal(
        g.bond_params_table.lookup(*p.i_seqs).weight, b0[i])
  for i, p in enumerate(g.angle_proxies):
    if rsm.angle_key(p.i_seqs) == angle_keys[0]:
      assert approx_equal(a1[i], a0[i])
  assert not approx_equal(b1, b0, out=None)
  assert not approx_equal(a1, a0, out=None)

def exercise_not_available():
  # no restraints
  pdb_inp = iotbx.pdb.input(source_info=None, lines=pdb_str)
  m = mmtbx.model.manager(model_input=pdb_inp, log=null_out())
  assert not m.apply_restraints_scale()
  assert not m.remove_restraints_scale()
  assert not m.scale_restraints(
    factor = 10., density_rank = flex.double(m.size(), 0.5))
  assert m.rsm is None

