"""reduce2: fine step and polish of multi-Mover Cliques.

A fine move of a Clique member is accepted only if it raises the Clique's total
(its own score and its neighbours'). After the fine step each multi-Mover Clique
is polished: each member in turn tries every coarse state with its own fine
search, the others fixed, and takes the candidate that raises the Clique's total
most; sweeps repeat until nothing moves. No sweep starts after the time limit.

Tests:
- test_gate: 7PRG hd_and_h Thr D 7 / Asn A 85 / Lys D 62 (alt A), polish off:
  Thr D 7's best fine pose raises its own score but lowers the Clique's, so it
  stays at its coarse pose; with the polish, no Clique ends below its coarse
  total. A guard: master's stored-score rule also keeps Thr D 7.
- test_polish: 4i8h hd_and_h Lys A 156 + Thr A 21 (alt B): the Clique ends
  within 0.25 of the best combination of each member's coarse states with their
  fine optima; each Mover the polish moved has a fresh stored score.
- test_current_state: 6vw1 Thr A 276 + Thr A 445: the polish must also try
  another pose around a member's current coarse state.
- test_deadline: with the time limit passed before the fine step the polish is
  skipped; with a limit that expires after the first accepted polish move that
  sweep finishes and no other starts. Poses stay consistent and no Clique ends
  below its coarse total.
- test_release: 6vw1: after each Clique's polish (also after the time limit)
  the members' fine-pose dots are released from the dot cache.
"""
