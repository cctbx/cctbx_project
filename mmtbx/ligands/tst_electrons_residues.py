def get_model(text):
  inp = iotbx.pdb.input(lines=text.splitlines(), source_info=None)
  model = mmtbx.model.manager(model_input=inp, log=null_out())
  model.process(make_restraints=True)
  return model

def charges_by_residue(ed):
  """{(resname, resseq): charge} summed over the atoms of each residue"""
  rc = {}
  for atom in ed.hierarchy.atoms():
    rg = atom.parent().parent()
    key = (rg.unique_resnames()[0], rg.resseq.strip())
    rc[key] = rc.get(key, 0) - ed[atom.i_seq]
  return rc

def his_variants(text):
  """the second HIS without HD1 (HIE), the third without HE2 (HID)"""
  his = []
  out = []
  for l in text.splitlines():
    if l.startswith("ATOM") and l[17:20] == "HIS":
      resseq = l[22:26]
      if resseq not in his:
        his.append(resseq)
      name = l[12:16].strip()
      i = his.index(resseq)
      if (i == 1 and name == "HD1") or (i == 2 and name == "HE2"):
        continue
    out.append(l)
  assert len(his) == 3, his
  return "\n".join(out) + "\n", his

def test_amino_acids():
  text, his = his_variants(pdb_amino_acids)
  ed = electrons.run(model=get_model(text), return_formal_charges=True)
  expected = dict(residue_charges)
  expected["HIS"] = None
  found = charges_by_residue(ed)
  assert len(found) == 22, len(found)
  for (resname, resseq), charge in sorted(found.items()):
    if resname == "HIS":
      want = {his[0].strip(): 1, his[1].strip(): 0, his[2].strip(): 0}[resseq]
    else:
      want = residue_charges[resname]
    assert charge == want, (resname, resseq, charge, want)
  assert ed.get_total_charge() == 1, ed.get_total_charge()
  # the charged atoms: the ring N of the HIS+, not a ring carbon
  for atom, e in ed.get_charged_atoms():
    if atom.parent().resname == "HIS":
      assert atom.name.strip() in ("N", "ND1", "NE2", "O", "OXT"), atom.quote()
      assert e == -1 or atom.name.strip() in ("O", "OXT"), (atom.quote(), e)

def test_nadp():
  """-3 every time: the ring double bonds are placed in a random order"""
  model = get_model(pdb_nap)
  for i in range(5):
    ed = electrons.run(model=model, return_formal_charges=True)
    assert ed.get_total_charge() == -3, (i, ed.get_total_charge())
    charged = dict((a.name.strip(), -e) for a, e in ed.get_charged_atoms())
    assert charged == {"N1N": 1, "O2A": -1, "O2N": -1, "O2X": -1, "O3X": -1}, \
      charged

