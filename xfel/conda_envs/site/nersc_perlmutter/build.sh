#!/bin/bash
#
# Build cctbx/DIALS (+ psana, CUDA, Kokkos) on NERSC Perlmutter.
# Run it, do not source it.
#
# The checkout directory is the install prefix: modules/, build/, mc3/, opt/
# and activate.sh are all created next to this script.  Clone the repo where you
# want the build to live ($CFS or $SCRATCH, not $HOME).

set -eo pipefail

[[ -z ${CONDA_PREFIX:-} ]] || { echo "conda env active; run 'conda deactivate' first" >&2; exit 1; }

ROOT_PREFIX=$(cd "$(dirname "$0")" && pwd)
CONDA_BASE=$ROOT_PREFIX/mc3
NPROC=32

MINIFORGE_VERSION=26.3.2-3
MINIFORGE=Miniforge3-$MINIFORGE_VERSION-Linux-x86_64.sh
MINIFORGE_URL=https://github.com/conda-forge/miniforge/releases/download/$MINIFORGE_VERSION/$MINIFORGE

# CUDA 13: cctbx branch cuda13-kokkos-4.7 (Kokkos 4.7.03, sm_75+ arch flags).
# Revert this commit once that branch is merged upstream.
BOOTSTRAP_COMMIT=3dbd09773a3788b9b695e45397f4bc59cd137546
BOOTSTRAP_URL=https://raw.githubusercontent.com/cctbx/cctbx_project/$BOOTSTRAP_COMMIT/libtbx/auto_build/bootstrap.py

BOOTSTRAP_FLAGS=(
    --builder=dials
    --python=310
    --nproc=$NPROC
    --config-flags=--cxxstd=c++14
    --config-flags=--no_bin_python
    --config-flags=--enable_openmp_if_possible=True
    --config-flags=--enable_cuda
    --config-flags=--enable_kokkos
    --config-flags=--use_environment_flags
    --no-boost-src
)

step () { printf '\n===== %s -- %s\n' "$*" "$(date '+%F %T')"; }

# Python block-buffers stdout when it is not a tty, which scrambles bootstrap.py's
# banners in a redirected log.
export PYTHONUNBUFFERED=1

# Read by simtbx/kokkos's SConscript during the scons build.
export OMP_PLACES=threads
export OMP_PROC_BIND=false
export KOKKOS_DEVICES="OpenMP;Cuda"
export KOKKOS_ARCH="Ampere80"

cd "$ROOT_PREFIX"
mkdir -p opt

step "download bootstrap.py and Miniforge3"
wget -O bootstrap.py "$BOOTSTRAP_URL"
wget -O "opt/$MINIFORGE" "$MINIFORGE_URL"

step "install Miniforge3 into $CONDA_BASE"
bash "opt/$MINIFORGE" -b -u -p "$CONDA_BASE"   # -b: no prompts, no conda init.  -u: re-runnable.

step "module load PrgEnv-gnu cudatoolkit cpe-cuda"
module load PrgEnv-gnu cudatoolkit cpe-cuda

source "$CONDA_BASE/etc/profile.d/conda.sh"

# Capture the Cray wrapper BEFORE `conda activate`: the env's c-compiler package
# shadows `cc` with a conda shim, and mpi4py then links against the wrong MPI.
native_cc=$(which cc)

step "conda env create (5-10 min)"
conda env create -f perlmutter_environment.yml --yes -v
conda activate psana_env

# gemmi is deliberately not in the yml -- it makes the solve pathological.  It is
# a pure runtime dependency (dials.export/dials.merge), nothing in the build
# needs it, and it must go in before the MPI strip leaves the prefix inconsistent.
step "install gemmi"
conda install -y -p "$CONDA_PREFIX" -c conda-forge --override-channels --no-deps -v gemmi

# psana pulls in openmpi, which is incompatible with Cray MPICH.  The remove
# routinely fails partially, hence `|| true`.
step "rebuild mpi4py against Cray MPICH"
conda remove --force mpi4py mpi openmpi mpich --yes || true
MPICC="$native_cc -shared -target-accel=nvidia80 -lmpi -lgdrapi" \
    pip install -v --no-binary mpi4py --no-cache-dir mpi4py mpi4py

step "bootstrap.py hot update"
python bootstrap.py "${BOOTSTRAP_FLAGS[@]}" --use-conda "$CONDA_PREFIX" hot update
git -C modules/cctbx_project fetch origin cuda13-kokkos-4.7
git -C modules/cctbx_project checkout $BOOTSTRAP_COMMIT

step "bootstrap.py build"
python bootstrap.py "${BOOTSTRAP_FLAGS[@]}" --use-conda "$CONDA_PREFIX" build

step "write activate.sh"
cat > activate.sh << EOF
# Generated by build.sh.  SOURCE this file, do not execute it.
export ROOT_PREFIX=$ROOT_PREFIX

module load PrgEnv-gnu cudatoolkit cpe-cuda
source $CONDA_BASE/etc/profile.d/conda.sh
conda activate psana_env
source $ROOT_PREFIX/build/setpaths.sh

export OMP_PLACES=threads
export OMP_PROC_BIND=false
export KOKKOS_DEVICES="OpenMP;Cuda"
export KOKKOS_ARCH="Ampere80"
export CUDA_LAUNCH_BLOCKING=1
export MPI4PY_RC_RECV_MPROBE='False'
export SIT_DATA=/global/common/software/lcls/psdm/data:\$SIT_DATA
export SIT_PSDM_DATA=/pscratch/sd/p/psdatmgr/psdm/
export SIT_ROOT=/reg/g/psdm

# Incremental rebuild:  mk-cctbx build         (recompile only)
#                       mk-cctbx build hot update  (re-fetch sources first)
mk-cctbx () {
    (cd \$ROOT_PREFIX && python bootstrap.py ${BOOTSTRAP_FLAGS[*]} --use-conda \$CONDA_PREFIX "\$@")
}
EOF

printf '\nDone.  Source %s/activate.sh to use this installation.\n' "$ROOT_PREFIX"
