#!/bin/bash
#
# Build cctbx/DIALS (+ psana, CUDA, Kokkos) on NERSC Perlmutter.
# Run it, do not source it.
#
# modules/cctbx_project is your clone of this repo; build/, mc3/, conda_base/,
# opt/, activate.sh and bootstrap.py are created next to modules/.  Clone
# where you want the build to live ($CFS or $SCRATCH, not $HOME):
#
#   git clone https://github.com/cctbx/cctbx_project $PREFIX/modules/cctbx_project
#   $PREFIX/modules/cctbx_project/xfel/conda_envs/site/nersc_perlmutter/build.sh

set -eo pipefail

[[ -z ${CONDA_PREFIX:-} ]] || { echo "conda env active; run 'conda deactivate' first" >&2; exit 1; }

case "${PSANA_CHANNEL:-}" in
    lcls-i|lcls-ii|none) ;;
    *) echo "set PSANA_CHANNEL=lcls-i (psana1) or lcls-ii (psana2) or none" >&2; exit 1 ;;
esac

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
BUILD_PREFIX=$(cd "$SCRIPT_DIR/../../../../../.." && pwd)
MINIFORGE_PREFIX=$BUILD_PREFIX/mc3
[[ ! -e $MINIFORGE_PREFIX ]] || { echo "$BUILD_PREFIX already has a build; use mk-cctbx, or delete mc3/ and conda_base/ to start over" >&2; exit 1; }
ENV_PREFIX=$BUILD_PREFIX/conda_base
NPROC=32

MINIFORGE_VERSION=26.3.2-3
MINIFORGE=Miniforge3-$MINIFORGE_VERSION-Linux-x86_64.sh
MINIFORGE_URL=https://github.com/conda-forge/miniforge/releases/download/$MINIFORGE_VERSION/$MINIFORGE

BOOTSTRAP_FLAGS=(
    --builder=xfel
    --nproc=$NPROC
    --config-flags=--no_bin_python
    --config-flags=--enable_cuda
    --config-flags=--enable_kokkos
    --config-flags=--use_environment_flags
    --no-boost-src
)

step () { printf '\n===== %s -- %s\n' "$*" "$(date '+%F %T')"; }

# Python block-buffers stdout when it is not a tty, which scrambles bootstrap.py's
# banners in a redirected log.
export PYTHONUNBUFFERED=1

# Read by simtbx/kokkos's SConscript during the scons build.
export OMP_PLACES=threads
export OMP_PROC_BIND=false
export KOKKOS_DEVICES="OpenMP;Cuda"
export KOKKOS_ARCH="Ampere80"

cd "$BUILD_PREFIX"
mkdir -p opt

step "copy bootstrap.py and download Miniforge3"
cp modules/cctbx_project/libtbx/auto_build/bootstrap.py bootstrap.py
wget -O "opt/$MINIFORGE" "$MINIFORGE_URL"

step "install Miniforge3 into $MINIFORGE_PREFIX"
bash "opt/$MINIFORGE" -b -p "$MINIFORGE_PREFIX"

step "module load PrgEnv-gnu cudatoolkit cpe-cuda"
module load PrgEnv-gnu cudatoolkit cpe-cuda

source "$MINIFORGE_PREFIX/etc/profile.d/conda.sh"

# Capture the Cray wrapper BEFORE `conda activate`
native_cc=$(which cc)

step "conda env create (5-10 min)"
YMLFILE="$BUILD_PREFIX/opt/environment.yml"
cp "$SCRIPT_DIR/perlmutter_environment.yml" "$YMLFILE"
case "$PSANA_CHANNEL" in
    lcls-i)
      PSANA_SPEC='psana=4.0.66'
      PYVERSION='3.11'
      ;;
    lcls-ii)
      PSANA_SPEC='psana'
      PYVERSION='3.13'
      ;;
    none)
      PSANA_SPEC='none'
      PYVERSION='3.13'
      sed -i "/__PSANA/d" $YMLFILE
esac
sed -i -e "s/__PSANA_CHANNEL__/$PSANA_CHANNEL/" -e "s/__PSANA__/$PSANA_SPEC/" \
    -e "s/__PYVERSION__/$PYVERSION/" $YMLFILE
conda env create -f "$BUILD_PREFIX/opt/environment.yml" -p "$ENV_PREFIX" -v

conda activate "$ENV_PREFIX"

# Install gemmi separately to avoid solver problems
step "install gemmi"
conda install -y -p "$ENV_PREFIX" -c conda-forge --override-channels --no-deps -v gemmi

# psana pulls in openmpi, which is incompatible with Cray MPICH.  The remove
# routinely fails partially, hence `|| true`.
step "rebuild mpi4py against Cray MPICH"
conda remove --force mpi4py mpi openmpi mpich --yes || true
MPICC="$native_cc -shared -target-accel=nvidia80 -lmpi -lgdrapi" \
    pip install -v --no-binary mpi4py --no-cache-dir mpi4py mpi4py

step "write activate.sh"
cat > activate.sh << EOF
# Generated by build.sh.  SOURCE this file, do not execute it.
export BUILD_PREFIX=$BUILD_PREFIX

module load PrgEnv-gnu cudatoolkit cpe-cuda
source $MINIFORGE_PREFIX/etc/profile.d/conda.sh
conda activate $ENV_PREFIX
source $BUILD_PREFIX/build/setpaths.sh

export OMP_PLACES=threads
export OMP_PROC_BIND=false
export KOKKOS_DEVICES="OpenMP;Cuda"
export KOKKOS_ARCH="Ampere80"
export CUDA_LAUNCH_BLOCKING=1
export MPI4PY_RC_RECV_MPROBE='False'
export SIT_DATA=/global/common/software/lcls/psdm/data:\$SIT_DATA
export SIT_PSDM_DATA=/pscratch/sd/p/psdatmgr/psdm/
export SIT_ROOT=/reg/g/psdm

# Incremental rebuild (same verbs as bootstrap.py):
#   mk-cctbx build                  # Recompile only
#   mk-cctbx hot update build       # Re-fetch sources, build
#   mk-cctbx                        # Recompile only. Equivalent to mk-cctbx build
mk-cctbx () {
    (cd \$BUILD_PREFIX && python bootstrap.py ${BOOTSTRAP_FLAGS[*]} --use-conda \$CONDA_PREFIX "\${@:-build}")
}
EOF

step "bootstrap.py hot update"
python bootstrap.py "${BOOTSTRAP_FLAGS[@]}" --use-conda "$ENV_PREFIX" hot update

step "bootstrap.py build"
python bootstrap.py "${BOOTSTRAP_FLAGS[@]}" --use-conda "$ENV_PREFIX" build

printf '\nDone.  Source %s/activate.sh to use this installation.\n' "$BUILD_PREFIX"
